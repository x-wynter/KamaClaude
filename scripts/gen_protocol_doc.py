#!/usr/bin/env python3
# 维护脚本：从 Pydantic 模型取得 JSON Schema，拼接生成 WIRE_PROTOCOL.md。
# 默认写文件；--check 只比较内容并通过退出码报告文档是否同步。

"""Generate WIRE_PROTOCOL.md from pydantic models in kama.core.bus."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from kama_claude.core.bus.commands import PingCommand, PongResult
from kama_claude.core.bus.events import CoreStartedEvent

# __file__ 是当前脚本文件路径；两次 parent 回到项目根目录，再拼接输出文件名。
_OUTPUT_PATH = Path(__file__).parent.parent / "WIRE_PROTOCOL.md"


# 把一个模型转换成 Markdown 小节：字段表 + JSON Schema + 可选示例。
def _model_section(name: str, model: type, example: dict | None = None) -> str:  # type: ignore[type-arg]
    # 传入的是模型类而非实例；model_json_schema 描述字段规则，不是某次请求数据。
    # type: ignore 是给 mypy 的局部检查豁免，不改变 Python 的运行行为。
    schema = model.model_json_schema()  # type: ignore[attr-defined]
    props = schema.get("properties", {})
    # Schema 的 required 列出必填字段，转为集合方便后续用 in 检查。
    required: set[str] = set(schema.get("required", []))

    table = ""
    if props:
        table = "\n| Field | Type | Required |\n|---|---|---|\n"
        # items 逐次给出键值对，并解包为字段名及该字段的 Schema。
        for field_name, field_info in props.items():
            ftype = field_info.get("type", "object")
            if "anyOf" in field_info:
                # 生成器表达式逐个取候选类型，join 用分隔符拼接为文字说明。
                ftype = " | ".join(t.get("type", "?") for t in field_info["anyOf"])
            req = "yes" if field_name in required else "no"
            table += f"| `{field_name}` | `{ftype}` | {req} |\n"

    # json.dumps(indent=2) 生成两空格缩进的 JSON 文本；反引号组成 Markdown 代码块。
    schema_block = f"\n```json\n{json.dumps(schema, indent=2)}\n```\n"

    example_block = ""
    # 只有示例字典非空时才展示；None 和空字典都会跳过。
    if example:
        example_block = f"\n**Example:**\n\n```json\n{json.dumps(example, indent=2)}\n```\n"

    return f"### {name}\n{table}{schema_block}{example_block}"


# 汇总协议说明、模型小节和示例，返回完整文档字符串。
def generate() -> str:
    # 示例是手写的完整请求，Schema 来自业务模型；两者所处协议层次不同。
    ping_req_example = {
        "jsonrpc": "2.0",
        "id": "u-1",
        "method": "core.ping",
        "params": {"client": "cli/0.0.1"},
    }
    pong_resp_example = {
        "jsonrpc": "2.0",
        "id": "u-1",
        "result": {
            "server_version": "0.0.1",
            "uptime_ms": 12,
            "received_at": "2026-05-11T07:31:14.022Z",
        },
    }

    # 用列表保存各段文字，最后统一拼接；此处仅构造字符串，没有文件操作。
    sections = [
        "# Wire Protocol\n\n",
        "> Generated by `scripts/gen_protocol_doc.py`. **Do not edit manually.**\n\n",
        "## Transport\n\n",
        "- TCP loopback `127.0.0.1:7437` (override via `KAMA_HOST` / `KAMA_PORT`)\n",
        "- Each message is one `\\n`-terminated JSON line (NDJSON)\n",
        "- Commands use JSON-RPC 2.0; Events use a custom `kind=event` envelope\n\n",
        "## Commands\n\n",
        _model_section("PingCommand", PingCommand, ping_req_example),
        "\n",
        _model_section("PongResult", PongResult, pong_resp_example),
        "\n## Events\n\n",
        _model_section("CoreStartedEvent", CoreStartedEvent),
        "\n## Error Codes\n\n",
        "| Code | Name | Meaning |\n",
        "|------|------|---------|\n",
        "| -32700 | Parse Error | Invalid JSON received |\n",
        "| -32600 | Invalid Request | Missing required JSON-RPC fields |\n",
        "| -32601 | Method Not Found | Unknown method |\n",
        "| -32602 | Invalid Params | Parameter validation failed |\n",
        "| -32603 | Internal Error | Handler raised an unhandled exception |\n",
    ]
    # 空字符串作分隔符，把所有段落按顺序连接。
    return "".join(sections)


# 解析生成脚本的参数，然后选择检查已有文件或写入生成内容。
def main() -> None:
    parser = argparse.ArgumentParser(description="Generate WIRE_PROTOCOL.md")
    # store_true 表示开关；--output 则需要路径参数，省略时使用默认路径。
    parser.add_argument("--check", action="store_true", help="Verify file matches generated output")
    parser.add_argument("--output", default=str(_OUTPUT_PATH))
    args = parser.parse_args()

    content = generate()

    # 检查模式：缺少文件或内容不同均以状态码 1 退出，不会改写文档。
    if args.check:
        output_path = Path(args.output)
        if not output_path.exists():
            print(f"ERROR: {output_path} not found — run: make docs", file=sys.stderr)
            sys.exit(1)
        if output_path.read_text() != content:
            print(f"ERROR: {output_path} out of sync with code — run: make docs", file=sys.stderr)
            sys.exit(1)
        print(f"OK: {output_path} is up to date.")
    else:
        output_path = Path(args.output)
        output_path.write_text(content)
        print(f"Generated {output_path}")


# 直接运行脚本时 __name__ 为 __main__；作为模块导入时不自动执行 main。
if __name__ == "__main__":
    main()
